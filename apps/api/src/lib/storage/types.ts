import type { UploadContentType } from "@primegear/shared";

export type UploadTarget = {
  url: string;
  method: "PUT";
  /** Headers the browser must send with the PUT (they are part of the signature) */
  headers: Record<string, string>;
  expiresAt: Date;
};

export type StoredObject = { size: number; contentType: string | null };

/**
 * Where uploaded images live. The browser uploads straight to the storage (a presigned URL), the API
 * only signs. Drivers: `local` (disk, development) and `r2` (Cloudflare R2, production), chosen by
 * STORAGE_DRIVER. Keys look like `stores/<storeId>/products/2026/10/<random>.webp`.
 */
export interface StorageProvider {
  readonly driver: "local" | "r2";
  /** A short-lived URL the browser PUTs the file to */
  createUpload(input: {
    key: string;
    contentType: UploadContentType;
    size: number;
  }): Promise<UploadTarget>;
  /** Size and type of an uploaded object, or null when it does not exist */
  head(key: string): Promise<StoredObject | null>;
  /** Removes the object; deleting a missing key is not an error */
  delete(key: string): Promise<void>;
  /** Public URL the storefront renders */
  publicUrl(key: string): string;
  /** The key behind one of our public URLs, or null for any other URL */
  keyFromUrl(url: string): string | null;
}

/** Keys are generated by the API, but uploads and deletes still refuse anything that could escape the root */
export const isSafeKey = (key: string) =>
  /^[a-z0-9][a-z0-9/_.-]{0,299}$/i.test(key) && !key.split("/").some((s) => s === "" || s === "." || s === "..");
